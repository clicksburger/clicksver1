import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
import { createRequire } from "node:module";
import ts from "typescript";

const source = fs.readFileSync(new URL("../src/features/menu/store/cart.store.ts", import.meta.url), "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } });
const exported = {};
vm.runInNewContext(compiled.outputText, { exports: exported, require: createRequire(import.meta.url) });
const { useCartStore, cartToPedidoItems, cartTotal } = exported;
const item = { itemId: "papas", nombre: "PAPAS FRITAS", variante: null, precio: 3500 };
useCartStore.getState().add({ ...item, obs: "sin sal" });
useCartStore.getState().add({ ...item, obs: " sin sal " });
useCartStore.getState().add({ ...item, obs: "bien doradas" });
let lines = useCartStore.getState().lines;
assert.equal(lines.length, 2, "No combina notas distintas");
assert.equal(lines[0].cantidad, 2, "Combina configuraciones idénticas");
assert.equal(cartToPedidoItems(lines)[0].obs, "sin sal", "Conserva notas en el payload del pedido");
assert.equal(cartTotal(lines), 10500);
useCartStore.getState().add({ itemId: "dip", nombre: "DIP DE SALSAS", variante: "Mayo Clicks + Ketchup", precio: 500, obs: "x".repeat(180) });
lines = useCartStore.getState().lines;
assert.equal(lines[2].obs.length, 150, "Limita notas también en el store");
assert.equal(cartTotal(lines), 11000, "Un dip con varias salsas conserva el precio por porción");
useCartStore.getState().remove(lines[1].key);
assert.equal(useCartStore.getState().lines.length, 2);
useCartStore.getState().clear();
assert.equal(cartTotal(useCartStore.getState().lines), 0);
console.log("Carrito: notas, límite de 150 caracteres, cantidades, payload y total verificados.");
